"""Generate cmd/bench/bench_data.mbt: the fixtures `scripts/bench.py` reads
from upstream Rich (first 2,000 lines of rich/console.py, README.md)."""

from pathlib import Path

RICH = Path("/Users/dii/git/rich.mbt/.repos/rich")
OUT = Path(__file__).parent.parent / "cmd" / "bench" / "bench_data.mbt"


def literal(name: str, text: str) -> str:
    assert "\r" not in text and text.endswith("\n")
    lines = [f"///|\nlet {name} : String =\n"]
    for line in text.split("\n")[:-1]:
        lines.append(f"  #|{line}\n")
    lines.append("  #|\n")
    return "".join(lines)


source = "".join(
    (RICH / "rich" / "console.py").read_text().splitlines(keepends=True)[:2000]
)
readme = (RICH / "README.md").read_text()
OUT.write_text(
    "// Generated by scripts/gen_bench_data.py from upstream Rich; do not edit.\n\n"
    + literal("python_source", source)
    + "\n"
    + literal("readme", readme)
)
