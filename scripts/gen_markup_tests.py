def markup_tests():
    lines = [HEADER, "", "///|", 'test "markup oracle cases" {']
    lines.append("  let cases : Array[(String, String)] = [")
    for c in MARKUP_CASES:
        try:
            out = text_repr(render(c))
        except MarkupError as e:
            out = "MarkupError: " + str(e)
        lines.append(f"    ({mbt_str(c)}, {mbt_str(out)}),")
    lines += ["  ]", "  for case in cases {", "    assert_eq(render_case(case.0), case.1)", "  }", "}", ""]
    lines += ["///|", 'test "escape oracle cases" {']
    lines.append("  let cases : Array[(String, String, String)] = [")
    for c in ESCAPE_CASES:
        escaped = escape(c)
        lines.append(f"    ({mbt_str(c)}, {mbt_str(escaped)}, {mbt_str(render(escaped).plain)}),")
    lines += [
        "  ]",
        "  for case in cases {",
        "    assert_eq(@rich.escape(case.0), case.1)",
        "    assert_eq(@rich.render_markup(case.1).plain(), case.2)",
        "  }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def literal_tests():
    lines = [HEADER, "", "///|", 'test "literal_eval oracle cases" {']
    lines.append("  let cases : Array[(String, String)] = [")
    for c in LITERAL_CASES:
        try:
            out = "OK " + repr(literal_eval(c))
        except SyntaxError as e:
            out = "SyntaxError " + e.msg
        except Exception as e:
            out = type(e).__name__ + " " + str(e)
        lines.append(f"    ({mbt_str(c)}, {mbt_str(out)}),")
    lines += ["  ]", "  for case in cases {", "    assert_eq(literal_eval_case(case.0), case.1)", "  }", "}"]
    return "\n".join(lines) + "\n"


