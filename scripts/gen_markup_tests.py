def mbt_str(s: str) -> str:
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif o < 0x20 or o == 0x7F:
            out.append("\\u{%x}" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def delist(v):
    if isinstance(v, (tuple, list)):
        return [delist(x) for x in v]
    if isinstance(v, dict):
        return {k: delist(x) for k, x in v.items()}
    return v


def u16(plain: str, offset: int) -> int:
    return len(plain[:offset].encode("utf-16-le")) // 2


def span_repr(plain, span):
    style = span.style
    start, end = u16(plain, span.start), u16(plain, span.end)
    if isinstance(style, Style):
        return f"Span({start}, {end}, meta={delist(style.meta)!r})"
    return f"Span({start}, {end}, {style!r})"


def text_repr(t):
    spans = ", ".join(span_repr(t.plain, s) for s in t.spans)
    return f"<text {t.plain!r} [{spans}] {t.style!r}>"


